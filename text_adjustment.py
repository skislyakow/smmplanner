import re


def text_adjustment(text: str) -> str:
    """Очищает текст от лишних символов и правит кавычки/тире."""
    if not text:
        return ""

    # Порядок правил критически важен!
    rules = [
        # 1. Сначала меняем тире (пока не удалены пробелы вокруг них)
        (r"\s+--?\s+", " — "),
        # 2. Убираем пробелы ПЕРЕД знаками препинания
        (r"\s+([.,!?;:])", r"\1"),
        # 3. Кавычки: используем ленивый поиск (.*?) вместо ([^"]*)
        #    и исключаем перенос строки, чтобы кавычки не прыгали через абзацы
        (r'"([^"\n]*?)"', r"«\1»"),
        (r"'([^'\n]*?)'", r"«\1»"),
        # 4. Удаляем лишние пробелы в строках, сохраняя перенос абзацев
        (r"[ \t]+", " "),  # только горизонтальные пробелы и табы
        (r" +$| +^", ""),  # удаляем пробелы в начале и конце строк (мультилайн)
    ]

    for pattern, replacement in rules:
        # Флаг re.MULTILINE нужен для корректного удаления пробелов в начале/конце строк
        text = re.sub(pattern, replacement, text, flags=re.MULTILINE)

    # В финале убираем лишние пустые строки (оставляем максимум одну между абзацами)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


# --- Тест работы ---
test_text = """
Пример   текста -- тут лишние пробелы , знак препинания отлетел .
Текст в "двойных кавычках" и 'одинарных'.

Новый абзац - здесь дефис стал тире.
"""

print(text_adjustment(test_text))